/// Boxed error type used by the streaming body wrappers.
pub type BoxError = Box<dyn StdError + Send + Sync>;

/// Context needed to build upstream request headers.
#[derive(Debug)]
pub struct ForwardCtx<'a> {
    /// Tunnel id (for audit headers).
    pub tunnel_id: &'a str,
    /// Direct client IP.
    pub client_ip: IpAddr,
    /// Request id generated by the gateway.
    pub request_id: &'a str,
    /// Original `Host` header, if any.
    pub original_host: Option<&'a str>,
    /// `https` or `http`, for `x-forwarded-proto`.
    pub scheme: &'a str,
    /// Optional replacement upstream API key.
    pub upstream_key: Option<&'a str>,
    /// How to handle inbound authentication headers.
    pub upstream_auth: UpstreamAuth,
}

/// Whether a header is hop-by-hop and must not be forwarded.
pub fn is_hop_by_hop(name: &HeaderName) -> bool {
    matches!(
        name.as_str(),
        "connection"
            | "keep-alive"
            | "proxy-authenticate"
            | "proxy-authorization"
            | "te"
            | "trailer"
            | "transfer-encoding"
            | "upgrade"
            | "expect"
    ) || name.as_str().starts_with("proxy-")
}

/// Whether a header is managed by the gateway and must be stripped from clients.
fn is_gateway_managed(name: &HeaderName) -> bool {
    matches!(
        name.as_str(),
        "host"
            | "content-length"
            | "authorization"
            | "x-api-key"
            | "x-request-id"
            | "x-real-ip"
            | "forwarded"
            | "x-divertlink-tunnel"
            | "x-divertlink-error"
    ) || name.as_str().starts_with("x-forwarded-")
}

/// Build sanitised headers for an upstream request.
///
/// * strips hop-by-hop and gateway-managed headers (prevents request smuggling
///   via `Connection: Content-Length` style tricks and header spoofing),
/// * optionally replaces or forwards authentication,
/// * adds `X-Forwarded-*`, `X-Request-Id` and audit headers.
pub fn sanitize_request_headers(headers: &HeaderMap, ctx: &ForwardCtx<'_>) -> HeaderMap {
    let mut out = HeaderMap::with_capacity(headers.len() + 6);
    for (name, value) in headers.iter() {
        if is_hop_by_hop(name) || is_gateway_managed(name) {
            continue;
        }
        out.append(name.clone(), value.clone());
    }

    // Authentication handling.
    match ctx.upstream_auth {
        UpstreamAuth::Passthrough => {
            if let Some(value) = headers.get(header::AUTHORIZATION) {
                out.insert(header::AUTHORIZATION, value.clone());
            }
            if let Some(value) = headers.get("x-api-key") {
                out.insert("x-api-key", value.clone());
            }
        }
        UpstreamAuth::Authorization => {
            if let Some(key) = ctx.upstream_key {
                if let Ok(value) = HeaderValue::from_str(&format!("Bearer {key}")) {
                    out.insert(header::AUTHORIZATION, value);
                }
            }
        }
        UpstreamAuth::XApiKey => {
            if let Some(key) = ctx.upstream_key {
                if let Ok(value) = HeaderValue::from_str(key) {
                    out.insert("x-api-key", value);
                }
            }
        }
        UpstreamAuth::None => {}
    }

    // Forwarding metadata.
    if let Ok(value) = HeaderValue::from_str(&ctx.client_ip.to_string()) {
        out.insert("x-forwarded-for", value);
    }
    if let Ok(value) = HeaderValue::from_str(ctx.scheme) {
        out.insert("x-forwarded-proto", value);
    }
    if let Some(host) = ctx.original_host {
        if let Ok(value) = HeaderValue::from_str(host) {
            out.insert("x-forwarded-host", value);
        }
    }
    if let Ok(value) = HeaderValue::from_str(ctx.request_id) {
        out.insert("x-request-id", value.clone());
        out.insert("x-divertlink-request-id", value);
    }
    if let Ok(value) = HeaderValue::from_str(ctx.tunnel_id) {
        out.insert("x-divertlink-tunnel", value);
    }
    out
}

/// Build sanitised response headers returned to the public client.
pub fn sanitize_response_headers(headers: &HeaderMap) -> HeaderMap {
    let mut out = HeaderMap::with_capacity(headers.len());
    for (name, value) in headers.iter() {
        // Content-Length is intentionally preserved: the body is byte-for-byte
        // identical to the upstream response, so the length stays correct.
        if is_hop_by_hop(name) {
            continue;
        }
        out.append(name.clone(), value.clone());
    }
    out
}

/// Strip a mount prefix from a request path.
///
/// * `/home` + `/home` -> `Some("/")`
/// * `/home` + `/home/v1/models` -> `Some("/v1/models")`
/// * `/home` + `/homepage` -> `None` (prefix must end on a segment boundary)
/// * `/` + any path -> `Some(path)`
pub fn strip_mount(path: &str, mount: &str) -> Option<String> {
    let mount = mount.trim_end_matches('/');
    if mount.is_empty() || mount == "/" {
        return Some(if path.is_empty() {
            "/".to_string()
        } else {
            path.to_string()
        });
    }
    if path == mount {
        return Some("/".to_string());
    }
    path.strip_prefix(mount)
        .filter(|rest| rest.starts_with('/'))
        .map(|rest| rest.to_string())
}

/// Whether a path matches a public (unauthenticated) prefix.
pub fn matches_public_path(path: &str, public_paths: &[String]) -> bool {
    public_paths.iter().any(|p| {
        let p = p.trim_end_matches('/');
        if p.is_empty() || p == "/" {
            path == "/"
        } else {
            path == p || path.starts_with(&format!("{p}/"))
        }
    })
}

/// Join a base URI with a forwarded path + query.
pub fn join_upstream_uri(base: &Uri, path: &str, query: Option<&str>) -> Result<Uri> {
    let base_path = base.path().trim_end_matches('/');
    let path_part = if path.starts_with('/') {
        format!("{base_path}{path}")
    } else {
        format!("{base_path}/{path}")
    };
    let path_part = if path_part.is_empty() {
        "/".to_string()
    } else {
        path_part
    };
    let path_and_query = match query {
        Some(q) if !q.is_empty() => format!("{path_part}?{q}"),
        _ => path_part,
    };
    let paq: axum::http::uri::PathAndQuery = path_and_query
        .parse()
        .map_err(|e| Error::Internal(format!("invalid upstream URI `{path_and_query}`: {e}")))?;
    let mut parts = base.clone().into_parts();
    parts.path_and_query = Some(paq);
    Uri::from_parts(parts).map_err(|e| Error::Internal(format!("invalid upstream URI: {e}")))
}

/// Normalize a raw request target into a safe path.
pub fn normalize_request_path(path: &str) -> Result<String> {
    if !crate::util::is_safe_path(path) {
        return Err(Error::Protocol(format!("unsafe request path `{path}`")));
    }
    Ok(path.to_string())
}

/// Generate a request id.
pub fn new_request_id() -> String {
    format!("dl_{}", crate::util::hex(&crate::util::random_bytes(8)))
}

/// Build an OpenAI-style JSON error response.
pub fn error_response(status: StatusCode, code: &str, message: &str) -> Response {
    let payload = json!({
        "error": {
            "message": message,
            "type": code,
            "code": code,
            "param": null,
        }
    });
    let body = Body::from(serde_json::to_vec(&payload).unwrap_or_default());
    let mut response = Response::new(body);
    *response.status_mut() = status;
    response.headers_mut().insert(
        header::CONTENT_TYPE,
        HeaderValue::from_static("application/json; charset=utf-8"),
    );
    if let Ok(value) = HeaderValue::from_str(code) {
        response.insert_header_value("x-divertlink-error", value);
    }
    response
}

trait ResponseHeaderExt {
    fn insert_header_value(&mut self, name: &'static str, value: HeaderValue);
}

impl ResponseHeaderExt for Response {
    fn insert_header_value(&mut self, name: &'static str, value: HeaderValue) {
        self.headers_mut().insert(name, value);
    }
}

/// Add a `Retry-After` header (whole seconds, minimum 1).
pub fn set_retry_after(response: &mut Response, retry: Duration) {
    let secs = retry.as_secs().max(1);
    if let Ok(value) = HeaderValue::from_str(&secs.to_string()) {
        response.headers_mut().insert(header::RETRY_AFTER, value);
    }
}

