/// A body wrapper that counts data frames into tunnel metrics.
///
/// `outbound == true` counts bytes sent to the public client (`bytes_out`),
/// otherwise bytes sent to the model server (`bytes_in`).
pub struct CountingBody<B> {
    inner: Pin<Box<B>>,
    stats: Arc<TunnelStats>,
    outbound: bool,
}

impl<B> CountingBody<B> {
    /// Wrap a body and account its data bytes.
    pub fn new(inner: B, stats: Arc<TunnelStats>, outbound: bool) -> Self {
        CountingBody {
            inner: Box::pin(inner),
            stats,
            outbound,
        }
    }
}

impl<B> HttpBody for CountingBody<B>
where
    B: HttpBody<Data = Bytes>,
    B::Error: Into<BoxError>,
{
    type Data = Bytes;
    type Error = BoxError;

    fn poll_frame(
        self: Pin<&mut Self>,
        cx: &mut Context<'_>,
    ) -> Poll<Option<std::result::Result<Frame<Self::Data>, Self::Error>>> {
        let this = self.get_mut();
        match this.inner.as_mut().poll_frame(cx) {
            Poll::Ready(Some(Ok(frame))) => {
                if let Some(data) = frame.data_ref() {
                    let len = data.len() as u64;
                    if this.outbound {
                        this.stats.add_bytes_out(len);
                    } else {
                        this.stats.add_bytes_in(len);
                    }
                }
                Poll::Ready(Some(Ok(frame)))
            }
            Poll::Ready(Some(Err(e))) => Poll::Ready(Some(Err(e.into()))),
            Poll::Ready(None) => Poll::Ready(None),
            Poll::Pending => Poll::Pending,
        }
    }

    fn size_hint(&self) -> SizeHint {
        self.inner.as_ref().size_hint()
    }

    fn is_end_stream(&self) -> bool {
        self.inner.as_ref().is_end_stream()
    }
}

/// A body wrapper enforcing a maximum quiet period between data frames.
///
/// This protects long-lived SSE streams from half-open connections: if the
/// upstream stops sending chunks for `idle` the body fails with a timeout and
/// the tunnel stream is torn down.
pub struct IdleTimeoutBody<B> {
    inner: Pin<Box<B>>,
    sleep: Pin<Box<Sleep>>,
    idle: Duration,
    finished: bool,
}

impl<B> IdleTimeoutBody<B> {
    /// Wrap a body with an idle timeout.
    pub fn new(inner: B, idle: Duration) -> Self {
        IdleTimeoutBody {
            inner: Box::pin(inner),
            sleep: Box::pin(tokio::time::sleep(idle)),
            idle,
            finished: false,
        }
    }
}

impl<B> HttpBody for IdleTimeoutBody<B>
where
    B: HttpBody<Data = Bytes>,
    B::Error: Into<BoxError>,
{
    type Data = Bytes;
    type Error = BoxError;

    fn poll_frame(
        self: Pin<&mut Self>,
        cx: &mut Context<'_>,
    ) -> Poll<Option<std::result::Result<Frame<Self::Data>, Self::Error>>> {
        let this = self.get_mut();
        if this.finished {
            return Poll::Ready(None);
        }
        match this.inner.as_mut().poll_frame(cx) {
            Poll::Ready(Some(Ok(frame))) => {
                this.sleep.as_mut().reset(Instant::now() + this.idle);
                Poll::Ready(Some(Ok(frame)))
            }
            Poll::Ready(Some(Err(e))) => {
                this.finished = true;
                Poll::Ready(Some(Err(e.into())))
            }
            Poll::Ready(None) => {
                this.finished = true;
                Poll::Ready(None)
            }
            Poll::Pending => match this.sleep.as_mut().poll(cx) {
                Poll::Ready(()) => {
                    this.finished = true;
                    Poll::Ready(Some(Err(Box::new(Error::Timeout(
                        "upstream stream idle timeout".into(),
                    )))))
                }
                Poll::Pending => Poll::Pending,
            },
        }
    }

    fn size_hint(&self) -> SizeHint {
        self.inner.as_ref().size_hint()
    }

    fn is_end_stream(&self) -> bool {
        self.inner.as_ref().is_end_stream()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::http::HeaderValue;

    #[test]
    fn strips_mounts() {
        assert_eq!(
            strip_mount("/home/v1/models", "/home").as_deref(),
            Some("/v1/models")
        );
        assert_eq!(strip_mount("/home", "/home").as_deref(), Some("/"));
        assert_eq!(strip_mount("/homepage", "/home"), None);
        assert_eq!(strip_mount("/anything", "/").as_deref(), Some("/anything"));
        assert_eq!(strip_mount("/", "/").as_deref(), Some("/"));
    }

    #[test]
    fn public_paths() {
        let paths = vec!["/health".to_string(), "/v1/models".to_string()];
        assert!(matches_public_path("/health", &paths));
        assert!(matches_public_path("/health/live", &paths));
        assert!(matches_public_path("/v1/models", &paths));
        assert!(!matches_public_path("/v1/chat/completions", &paths));
        assert!(!matches_public_path("/healthy", &paths));
    }

    #[test]
    fn header_sanitisation() {
        let mut headers = HeaderMap::new();
        headers.insert("connection", HeaderValue::from_static("keep-alive"));
        headers.insert("transfer-encoding", HeaderValue::from_static("chunked"));
        headers.insert("authorization", HeaderValue::from_static("Bearer client"));
        headers.insert("x-api-key", HeaderValue::from_static("sk-client"));
        headers.insert("content-type", HeaderValue::from_static("application/json"));
        headers.insert("host", HeaderValue::from_static("gateway.example.com"));
        headers.insert("x-forwarded-for", HeaderValue::from_static("1.2.3.4"));
        headers.insert("x-request-id", HeaderValue::from_static("spoofed"));
        let ctx = ForwardCtx {
            tunnel_id: "home",
            client_ip: "203.0.113.9".parse().unwrap(),
            request_id: "dl_123",
            original_host: Some("gateway.example.com"),
            scheme: "https",
            upstream_key: Some("upstream-secret"),
            upstream_auth: UpstreamAuth::Passthrough,
        };
        let out = sanitize_request_headers(&headers, &ctx);
        assert!(!out.contains_key("connection"));
        assert!(!out.contains_key("transfer-encoding"));
        assert!(!out.contains_key("host"));
        assert_eq!(out.get("content-type").unwrap(), "application/json");
        assert_eq!(out.get("authorization").unwrap(), "Bearer client");
        assert_eq!(out.get("x-api-key").unwrap(), "sk-client");
        assert_eq!(out.get("x-forwarded-for").unwrap(), "203.0.113.9");
        assert_eq!(out.get("x-request-id").unwrap(), "dl_123");
        assert_eq!(out.get("x-forwarded-proto").unwrap(), "https");
        assert_eq!(out.get("x-divertlink-tunnel").unwrap(), "home");
    }

    #[test]
    fn header_replacement() {
        let mut headers = HeaderMap::new();
        headers.insert("authorization", HeaderValue::from_static("Bearer client"));
        let ctx = ForwardCtx {
            tunnel_id: "home",
            client_ip: "127.0.0.1".parse().unwrap(),
            request_id: "dl_x",
            original_host: None,
            scheme: "http",
            upstream_key: Some("upstream-secret"),
            upstream_auth: UpstreamAuth::Authorization,
        };
        let out = sanitize_request_headers(&headers, &ctx);
        assert_eq!(out.get("authorization").unwrap(), "Bearer upstream-secret");
        let ctx = ForwardCtx {
            upstream_auth: UpstreamAuth::None,
            ..ctx
        };
        let out = sanitize_request_headers(&headers, &ctx);
        assert!(!out.contains_key("authorization"));
    }

    #[test]
    fn response_sanitisation() {
        let mut headers = HeaderMap::new();
        headers.insert("connection", HeaderValue::from_static("keep-alive"));
        headers.insert("transfer-encoding", HeaderValue::from_static("chunked"));
        headers.insert(
            "content-type",
            HeaderValue::from_static("text/event-stream"),
        );
        headers.insert("content-length", HeaderValue::from_static("123"));
        let out = sanitize_response_headers(&headers);
        assert!(!out.contains_key("transfer-encoding"));
        assert!(!out.contains_key("connection"));
        assert_eq!(out.get("content-type").unwrap(), "text/event-stream");
        assert_eq!(out.get("content-length").unwrap(), "123");
    }

    #[test]
    fn joins_uris() {
        let base: Uri = "http://127.0.0.1:8000".parse().unwrap();
        assert_eq!(
            join_upstream_uri(&base, "/v1/chat/completions", Some("stream=true"))
                .unwrap()
                .to_string(),
            "http://127.0.0.1:8000/v1/chat/completions?stream=true"
        );
        let base: Uri = "http://127.0.0.1:8000/api".parse().unwrap();
        assert_eq!(
            join_upstream_uri(&base, "/v1/models", None)
                .unwrap()
                .to_string(),
            "http://127.0.0.1:8000/api/v1/models"
        );
        let base: Uri = "http://127.0.0.1:8000/".parse().unwrap();
        assert_eq!(
            join_upstream_uri(&base, "/", None).unwrap().to_string(),
            "http://127.0.0.1:8000/"
        );
    }

    #[tokio::test]
    async fn idle_timeout_passes_data_through() {
        use http_body_util::{BodyExt, Full};
        let mut body: Body = Body::new(IdleTimeoutBody::new(
            Full::new(Bytes::from_static(b"hello")),
            Duration::from_millis(500),
        ));
        let frame = body.frame().await.unwrap().unwrap();
        assert_eq!(frame.data_ref().unwrap(), &Bytes::from_static(b"hello"));
        assert!(body.frame().await.is_none());
    }

    #[tokio::test]
    async fn idle_timeout_trips_on_stall() {
        use http_body_util::BodyExt;
        // A body that never produces a frame: the wrapper must time out.
        let stalled: Body = Body::from_stream(futures_util::stream::pending::<
            std::result::Result<Bytes, std::io::Error>,
        >());
        let mut body: Body = Body::new(IdleTimeoutBody::new(stalled, Duration::from_millis(30)));
        let err = body.frame().await.expect("frame").expect_err("timeout");
        assert!(err.to_string().contains("idle"), "{err}");
    }

    #[tokio::test]
    async fn counting_body_updates_stats() {
        use http_body_util::{BodyExt, Full};
        let stats = Arc::new(TunnelStats::default());
        let body: Body = Body::new(CountingBody::new(
            Full::new(Bytes::from_static(b"1234567890")),
            stats.clone(),
            false,
        ));
        let _ = body.collect().await.unwrap();
        assert_eq!(
            stats.bytes_in.load(std::sync::atomic::Ordering::Relaxed),
            10
        );
    }
}
